/*
 * Content management (A4, A5, A6). Every action re-verifies the admin's ID token on the
 * server, validates with the same Zod schemas the public pages use, writes with the
 * Admin SDK, then refreshes the public pages.
 */

const IMAGE_TYPES = ['image/jpeg', 'image/png', 'image/webp'];
const MAX_IMAGE_BYTES = 5 * 1024 * 1024; // same limit as storage.rules

function logFailure(action: string, error: unknown) {
  console.error(`[admin] ${action} failed:`, error instanceof Error ? error.message : 'unknown');
}

/** Firestore rejects `undefined`; drop such keys (optional fields left empty). */
function withoutUndefined<T>(value: T): T {
  if (Array.isArray(value)) return value.map(withoutUndefined) as T;
  if (value && typeof value === 'object' && !(value instanceof Date)) {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([, v]) => v !== undefined)
        .map(([k, v]) => [k, withoutUndefined(v)]),
    ) as T;
  }
  return value;
}

/** Create or replace one content document. `id` is generated by the editor for new items. */
export async function saveContent(
  idToken: string,
  input: { collection: string; id: string; data: unknown },
): Promise<ActionResult<{ id: string }>> {
  if (!(await requireAdmin(idToken))) return { ok: false, error: 'unauthorized' };
  const { collection, id } = input;
  if (!isContentCollection(collection) || !docIdSchema.safeParse(id).success) {
    return { ok: false, error: 'validation' };
  }

  const parsed = contentInputSchemas[collection].safeParse(input.data);
  if (!parsed.success) {
    return { ok: false, error: 'validation', fieldErrors: contentFieldErrors(parsed.error) };
  }
  const data = parsed.data as Record<string, unknown>;

  try {
    const db = adminDb();
    if (SLUG_COLLECTIONS.includes(collection)) {
      const sameSlug = await db.collection(collection).where('slug', '==', data.slug).get();
      if (sameSlug.docs.some((d) => d.id !== id)) {
        return { ok: false, error: 'validation', fieldErrors: { slug: 'slugTaken' } };
      }
    }
    if (collection === 'portfolio') {
      const paths = [data.coverImage as string, ...(data.gallery as string[])];
      if (!portfolioPathsValid(id, paths)) {
        return { ok: false, error: 'validation', fieldErrors: { coverImage: 'invalidField' } };
      }
    }

    await db
      .collection(collection)
      .doc(id)
      .set({
        ...withoutUndefined(data),
        ...(collection === 'services' && { updatedAt: FieldValue.serverTimestamp() }),
      });
    revalidatePublicPages();
    return { ok: true, data: { id } };
  } catch (error) {
    logFailure('saveContent', error);
    return { ok: false, error: 'server' };
  }
}

/** Delete one content document (portfolio: also its images). */
export async function deleteContent(
  idToken: string,
  input: { collection: string; id: string },
): Promise<ActionResult<{ id: string }>> {
  if (!(await requireAdmin(idToken))) return { ok: false, error: 'unauthorized' };
  const { collection, id } = input;
  if (!isContentCollection(collection) || !docIdSchema.safeParse(id).success) {
    return { ok: false, error: 'validation' };
  }
  try {
    await adminDb().collection(collection).doc(id).delete();
    if (collection === 'portfolio') {
      await deleteFolder(`portfolio/${id}/`);
    }
    revalidatePublicPages();
    return { ok: true, data: { id } };
  } catch (error) {
    logFailure('deleteContent', error);
    return { ok: false, error: 'server' };
  }
}

/** Site settings (contact details, hero text) — the single settings/site document. */
const SITE_DOCUMENTS = {
  site: settingsInputSchema, // contact details, hero, FAQ, …
  about: aboutInputSchema, // About page (F8)
  legal: legalInputSchema, // Privacy, Terms, Cookie Policy
  company: companyInputSchema, // story, fact cards, partners, impact, offices
  support: supportInputSchema, // Support page
  press: pressInputSchema, // Press page: leadership, media, brand colours
} as const;
type SiteDocumentId = keyof typeof SITE_DOCUMENTS;
const isSiteDocumentId = (id: string): id is SiteDocumentId => Object.hasOwn(SITE_DOCUMENTS, id);

/** Save one of the single site documents (settings/site, about, legal, company). */
export async function saveSiteDocument(
  idToken: string,
  input: { id: string; data: unknown },
): Promise<ActionResult<{ id: string }>> {
  if (!(await requireAdmin(idToken))) return { ok: false, error: 'unauthorized' };
  const id = input.id;
  if (!isSiteDocumentId(id)) return { ok: false, error: 'validation' };
  const parsed = SITE_DOCUMENTS[id].safeParse(input.data);
  if (!parsed.success) {
    return { ok: false, error: 'validation', fieldErrors: contentFieldErrors(parsed.error) };
  }
  try {
    await adminDb().doc(`settings/${id}`).set(withoutUndefined(parsed.data));
    revalidatePublicPages();
    return { ok: true, data: { id } };
  } catch (error) {
    logFailure(`save settings/${id}`, error);
    return { ok: false, error: 'server' };
  }
}

/** Upload one portfolio image (JPG/PNG/WebP, ≤ 5 MB, checked by content) -> Storage path. */
export async function uploadPortfolioImage(
  idToken: string,
  formData: FormData,
): Promise<ActionResult<{ path: string }>> {
  if (!(await requireAdmin(idToken))) return { ok: false, error: 'unauthorized' };
  const itemId = formData.get('itemId');
  const file = formData.get('file');
  if (typeof itemId !== 'string' || !docIdSchema.safeParse(itemId).success) {
    return { ok: false, error: 'validation' };
  }
  if (!(file instanceof File) || file.size === 0) return { ok: false, error: 'validation' };
  if (!IMAGE_TYPES.includes(file.type)) return { ok: false, error: 'imageType' };
  if (file.size > MAX_IMAGE_BYTES) return { ok: false, error: 'imageTooLarge' };

  try {
    const bytes = Buffer.from(await file.arrayBuffer());
    if (!contentMatchesType(bytes, file.type)) return { ok: false, error: 'imageType' };
    const path = `portfolio/${itemId}/${Date.now()}-${safeFileName(file.name)}`;
    await saveFile(path, bytes, file.type);
    return { ok: true, data: { path } };
  } catch (error) {
    logFailure('uploadPortfolioImage', error);
    return { ok: false, error: 'server' };
  }
}

/** Upload a site image — hero, tool/partner logo, person photo (≤ 5 MB, checked by content). */
export async function uploadSiteImage(
  idToken: string,
  formData: FormData,
): Promise<ActionResult<{ path: string }>> {
  if (!(await requireAdmin(idToken))) return { ok: false, error: 'unauthorized' };
  const kind = formData.get('kind');
  const file = formData.get('file');
  if (typeof kind !== 'string' || !Object.hasOwn(SITE_IMAGE_KINDS, kind)) {
    return { ok: false, error: 'validation' };
  }
  if (!(file instanceof File) || file.size === 0) return { ok: false, error: 'validation' };
  const { folder, logo, pdf } = SITE_IMAGE_KINDS[kind as keyof typeof SITE_IMAGE_KINDS];
  const types = [
    ...IMAGE_TYPES,
    ...(logo ? ['image/svg+xml'] : []), // logos are often SVG
    ...(pdf ? ['application/pdf'] : []), // press documents, e.g. licences
  ];
  const typeError = pdf ? 'pressFileType' : logo ? 'logoType' : 'imageType';
  if (!types.includes(file.type)) return { ok: false, error: typeError };
  if (file.size > MAX_IMAGE_BYTES) return { ok: false, error: 'imageTooLarge' };

  try {
    const bytes = Buffer.from(await file.arrayBuffer());
    if (!contentMatchesType(bytes, file.type)) return { ok: false, error: typeError };
    const path = `${folder}/${Date.now()}-${safeFileName(file.name)}`;
    await saveFile(path, bytes, file.type);
    return { ok: true, data: { path } };
  } catch (error) {
    logFailure('uploadSiteImage', error);
    return { ok: false, error: 'server' };
  }
}
